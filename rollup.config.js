import svelte from "rollup-plugin-svelte";
import typescript from "@rollup/plugin-typescript";
import { nodeResolve } from "@rollup/plugin-node-resolve";
import commonjs from "@rollup/plugin-commonjs";
import sveltePreprocess from "svelte-preprocess";
import copy from "rollup-plugin-copy";
import { execFileSync } from "child_process";
import { env } from "process";

const isProd = env.BUILD === "production";

function gitOutput(args, fallback = "") {
  try {
    return execFileSync("git", args, { encoding: "utf8" }).trim();
  } catch {
    return fallback;
  }
}

/**
 * Four-character commit stamp for the Settings > Longform Extended > Build
 * row. CI sets GITHUB_SHA; a local build derives the same prefix from HEAD and
 * adds -dirty when tracked files are modified.
 */
function buildCommit() {
  if (env.GITHUB_SHA) {
    return env.GITHUB_SHA.slice(0, 4);
  }

  const sha = gitOutput(["rev-parse", "--short=4", "HEAD"], "local");
  const dirty = gitOutput(["status", "--porcelain", "--untracked-files=no"]);
  return `${sha}${dirty ? "-dirty" : ""}`;
}

const buildInfo = {
  name: "longform-build-info",
  transform(code, id) {
    if (!id.replaceAll("\\", "/").endsWith("/src/build-info.ts")) {
      return null;
    }
    return code
      .replaceAll("__LONGFORM_BUILD_COMMIT__", buildCommit())
      .replaceAll("__LONGFORM_BUILD_TIME__", new Date().toISOString());
  },
};

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ROLLUP
if you want to view the source visit the plugins github repository
*/
`;

const getPlugins = (...plugins) =>
  [
    svelte({
      emitCss: false,
      preprocess: sveltePreprocess(),
    }),
    typescript({
      sourceMap: !isProd,
      inlineSources: !isProd,
      rootDir: "./src",
    }),
    buildInfo,
    nodeResolve({ browser: true, dedupe: ["svelte"] }),
    commonjs({
      include: "node_modules/**",
    }),
  ].concat(plugins);

const BASE_CONFIG = {
  input: "src/main.ts",
  external: ["obsidian"],
};

const DEV_PLUGIN_CONFIG = {
  ...BASE_CONFIG,
  output: {
    dir: "test-longform-vault/.obsidian/plugins/longform",
    sourcemap: "inline",
    format: "cjs",
    exports: "default",
  },
  plugins: getPlugins(
    copy({
      targets: [
        {
          src: "manifest.json",
          dest: "test-longform-vault/.obsidian/plugins/longform/",
        },
        {
          src: "styles.css",
          dest: "test-longform-vault/.obsidian/plugins/longform/",
        },
      ],
      hook: "writeBundle",
      verbose: true,
      overwrite: true,
    })
  ),
};

const PROD_PLUGIN_CONFIG = {
  ...BASE_CONFIG,
  output: {
    dir: ".",
    sourcemap: !isProd,
    format: "cjs",
    exports: "default",
    banner,
  },
  plugins: getPlugins(),
};

const config = isProd ? PROD_PLUGIN_CONFIG : DEV_PLUGIN_CONFIG;

export default config;
